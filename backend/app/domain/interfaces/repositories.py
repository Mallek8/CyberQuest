from typing import Protocol

from app.domain.entities.achievement import Achievement, UserAchievement
from app.domain.entities.hint import HintRecord
from app.domain.entities.mission import Challenge, Mission
from app.domain.entities.progress import Attempt, UserProgress
from app.domain.entities.user import User


class UserRepository(Protocol):
    def get_by_id(self, user_id: str) -> User | None: ...

    def get_by_email(self, email: str) -> User | None: ...

    def get_by_username(self, username: str) -> User | None: ...

    def add(self, user: User) -> User: ...

    def add_xp(self, user_id: str, amount: int) -> User: ...


class MissionRepository(Protocol):
    def list_all(self) -> list[Mission]: ...

    def get_by_slug(self, slug: str) -> Mission | None: ...

    def get_challenge(self, mission_id: str) -> Challenge | None: ...


class ProgressRepository(Protocol):
    def get(self, user_id: str, mission_id: str) -> UserProgress | None: ...

    def list_for_user(self, user_id: str) -> list[UserProgress]: ...

    def save(self, progress: UserProgress) -> UserProgress: ...


class AttemptRepository(Protocol):
    def add(self, attempt: Attempt) -> Attempt: ...

    def xp_banked(self, user_id: str, mission_id: str) -> int: ...

    def count_for_user(self, user_id: str) -> int: ...

    def count_perfect_for_user(self, user_id: str) -> int: ...

    def list_recent_for_user(self, user_id: str, limit: int) -> list[tuple[Attempt, Mission]]: ...


class AchievementRepository(Protocol):
    def list_all(self) -> list[Achievement]: ...

    def unlocked_ids(self, user_id: str) -> set[str]: ...

    def list_for_user(self, user_id: str) -> list[UserAchievement]: ...

    def grant(self, user_id: str, achievement: Achievement) -> UserAchievement: ...


class HintRepository(Protocol):
    def add(self, hint: HintRecord) -> HintRecord: ...

    def list_for_mission(self, user_id: str, mission_id: str) -> list[HintRecord]: ...

    def count_for_user(self, user_id: str) -> int: ...
